// The following two examples have been compiled from C with the following command:
//
// ```bash
//  clang -O2 -emit-llvm -c <file.c> -o - | llc -march=bpf -filetype=obj -o <file.o>
// ```
//
// The C source code was the following:
//
// ```c
// #include <linux/ip.h>
// #include <linux/in.h>
// #include <linux/tcp.h>
// #include <linux/bpf.h>
//
// #define ETH_ALEN 6
// #define ETH_P_IP 0x0008 /* htons(0x0800) */
// #define TCP_HDR_LEN 20
//
// #define BLOCKED_TCP_PORT 0x9999
//
// struct eth_hdr {
//     unsigned char   h_dest[ETH_ALEN];
//     unsigned char   h_source[ETH_ALEN];
//     unsigned short  h_proto;
// };
//
// #define SEC(NAME) __attribute__((section(NAME), used))
// SEC(".classifier")
// int handle_ingress(struct __sk_buff *skb)
// {
//     void *data = (void *)(long)skb->data;
//     void *data_end = (void *)(long)skb->data_end;
//     struct eth_hdr *eth = data;
//     struct iphdr *iph = data + sizeof(*eth);
//     struct tcphdr *tcp = data + sizeof(*eth) + sizeof(*iph);
//
//     /* single length check */
//     if (data + sizeof(*eth) + sizeof(*iph) + sizeof(*tcp) > data_end)
//         return 0;
//     if (eth->h_proto != ETH_P_IP)
//         return 0;
//     if (iph->protocol != IPPROTO_TCP)
//         return 0;
//     if (tcp->source == BLOCKED_TCP_PORT || tcp->dest == BLOCKED_TCP_PORT)
//         return -1;
//     return 0;
// }
// char _license[] SEC(".license") = "GPL";
// ```
//
// This program, once compiled, can be injected into Linux kernel, with tc for instance. Sadly, we
// need to bring some modifications to the generated bytecode in order to run it: the three
// instructions with opcode 0x61 load data from a packet area as 4-byte words, where we need to
// load it as 8-bytes double words (0x79). The kernel does the same kind of translation before
// running the program, but rbpf does not implement this.
//
// In addition, the offset at which the pointer to the packet data is stored must be changed: since
// we use 8 bytes instead of 4 for the start and end addresses of the data packet, we cannot use
// the offsets produced by clang (0x4c and 0x50), the addresses would overlap. Instead we can use,
// for example, 0x40 and 0x50. See comments on the bytecode below to see the modifications.
//
// Once the bytecode has been (manually, in our case) edited, we can load the bytecode directly
// from the ELF object file. This is easy to do, but requires the addition of two crates in the
// Cargo.toml file (see comments above), so here we use just the hardcoded bytecode instructions
// instead.

#[test]
#[cfg(feature = "std")]
fn test_vm_block_port() {
    // To load the bytecode from an object file instead of using the hardcoded instructions,
    // use the additional crates commented at the beginning of this file (and also add them to your
    // Cargo.toml). See comments above.
    //
    // ---
    // extern crate elf;
    // use elf::endian::AnyEndian;
    // use elf::ElfBytes;
    // use std::path::PathBuf;
    //
    // let filename = "my_ebpf_object_file.o";
    //
    // let path = PathBuf::from(filename);
    // let file_data = std::fs::read(path).expect("Could not read file");
    // let slice = file_data.as_slice();
    // let file = ElfBytes::<AnyEndian>::minimal_parse(slice).expect("Fail to parse ELF file");
    //
    // let classifier_section_header = match file.section_header_by_name(".classifier") {
    //     Ok(Some(header)) => header,
    //     Ok(None) => panic!("No .classifier section found"),
    //     Err(e) => panic!("Error while searching for .classifier section: {}", e),
    // };
    //
    // let prog = file
    //     .section_data(&classifier_section_header)
    //     .expect("Failed to get .classifier section data").0;
    // ---

    let prog = &[
        0xb7, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // mov r0, 0
        0x79, 0x12, 0x50, 0x00, 0x00, 0x00, 0x00, 0x00, // ldxdw r2, [r1+80] (was ldxw)
        0x79, 0x11, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, // ldxdw r1, [r1+64] (was ldxw at +76)
        0xbf, 0x13, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // mov r3, r1
        0x07, 0x03, 0x00, 0x00, 0x36, 0x00, 0x00, 0x00, // add r3, 54
        0x2d, 0x23, 0x12, 0x00, 0x00, 0x00, 0x00, 0x00, // jgt r3, r2, +18
        0x69, 0x12, 0x0c, 0x00, 0x00, 0x00, 0x00, 0x00, // ldxh r2, [r1+12]
        0x55, 0x02, 0x10, 0x00, 0x08, 0x00, 0x00, 0x00, // jne r2, 8, +16
        0x71, 0x12, 0x17, 0x00, 0x00, 0x00, 0x00, 0x00, // ldxb r2, [r1+23]
        0x55, 0x02, 0x0e, 0x00, 0x06, 0x00, 0x00, 0x00, // jne r2, 6, +14
        0x18, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, // lddw r0, 0xffffffff
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // (lddw, upper 32 bits)
        0x79, 0x11, 0x22, 0x00, 0x00, 0x00, 0x00, 0x00, // ldxdw r1, [r1+34] (was ldxw)
        0xbf, 0x12, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // mov r2, r1
        0x57, 0x02, 0x00, 0x00, 0xff, 0xff, 0x00, 0x00, // and r2, 0xffff
        0x15, 0x02, 0x08, 0x00, 0x99, 0x99, 0x00, 0x00, // jeq r2, 0x9999, +8
        0x18, 0x02, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, // lddw r2, 0xffff0000
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // (lddw, upper 32 bits)
        0x5f, 0x21, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // and r1, r2
        0xb7, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, // mov r0, -1
        0x18, 0x02, 0x00, 0x00, 0x00, 0x00, 0x99, 0x99, // lddw r2, 0x99990000
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // (lddw, upper 32 bits)
        0x1d, 0x21, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, // jeq r1, r2, +1
        0xb7, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // mov r0, 0
        0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // exit
    ];

    #[rustfmt::skip]
    let packet = &mut [
        0x01, 0x23, 0x45, 0x67, 0x89, 0xab,
        0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54,
        0x08, 0x00, // ethertype
        0x45, 0x00, 0x00, 0x3b, // start ip_hdr
        0xa6, 0xab, 0x40, 0x00,
        0x40, 0x06, 0x96, 0x0f,
        0x7f, 0x00, 0x00, 0x01,
        0x7f, 0x00, 0x00, 0x01,
        // Program matches the next two bytes: 0x9999 returns 0xffffffff, else return 0.
        0x99, 0x99, 0xc6, 0xcc, // start tcp_hdr
        0xd1, 0xe5, 0xc4, 0x9d,
        0xd4, 0x30, 0xb5, 0xd2,
        0x80, 0x18, 0x01, 0x56,
        0xfe, 0x2f, 0x00, 0x00,
        0x01, 0x01, 0x08, 0x0a, // start data
        0x00, 0x23, 0x75, 0x89,
        0x00, 0x23, 0x63, 0x2d,
        0x71, 0x64, 0x66, 0x73,
        0x64, 0x66, 0x0au8
    ];

    let mut vm = rbpf::EbpfVmFixedMbuff::new(Some(prog), 0x40, 0x50).unwrap();
    vm.register_helper(helpers::BPF_TRACE_PRINTK_IDX, helpers::bpf_trace_printf)
        .unwrap();

    let res = vm.execute_program(packet).unwrap();
    println!("Program returned: {res:?} ({res:#x})");
    assert_eq!(res, 0xffffffff);
}

